export const SITES: LandingSite[] = SITE_RECORDS.map((site) => ({
  ...site,
  coordinateSource: site.verified
    ? "Approximate position from a secondary coordinate compilation; identified mission site"
    : site.coordinateSource,
  // The archive has Viking 2 debris, but no standalone Viking 2 lander story.
  equipmentId: site.id === "viking-2" ? undefined : SITE_EQUIPMENT[site.id] ?? site.equipmentId,
  coordinateReference: {
    label: `Wikipedia — artificial objects on ${site.planet === "moon" ? "the Moon" : "Mars"} (secondary coordinate compilation)`,
    url: `https://en.wikipedia.org/wiki/List_of_artificial_objects_on_${site.planet === "moon" ? "the_Moon" : "Mars"}`,
    note: "Reference for researching the map's existing coordinates. Mission pages below provide context, not a new coordinate measurement.",
  },
  sources: missionSources({ id: site.id, mission: site.mission, planet: site.planet }),
}));

export function sitesByPlanet(planet: Planet): LandingSite[] {
  return SITES.filter((s) => s.planet === planet);
}

export const SITE_COUNT = {
  moon: sitesByPlanet("moon").length,
  mars: sitesByPlanet("mars").length,
};
